#!/usr/bin/env python3
"""Generate static/css/elementary-palette.css from tailwind.css.

The compiled Tailwind bundle hard-codes the "olive" ramp. This script emits one
override per olive utility that points at role-based CSS variables, so the
elementary theme (static/css/elementary.css) can recolor every existing class
for light and dark without rebuilding Tailwind.
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
css = (root / "static/css/tailwind.css").read_text()
rules = []
for match in re.finditer(r"(\.[^{},]*olive-(\d+)[^{},]*)\{([^}]*)\}", css):
    selector, step, body = match.group(1), match.group(2), match.group(3)
    selector = "html " + selector
    out = []
    for decl in body.split(";"):
        prop = decl.split(":")[0].strip()
        if not prop:
            continue
        if prop in ("background-color", "--tw-gradient-from", "--tw-gradient-to"):
            role = "bg"
        elif prop == "color" or prop == "text-decoration-color":
            role = "fg"
        else:
            role = "bd"
        if prop == "--tw-gradient-from":
            out.append(f"--tw-gradient-from:var(--o-{role}-{step}) var(--tw-gradient-from-position);--tw-gradient-stops:var(--tw-gradient-from),var(--tw-gradient-to)")
        elif prop == "--tw-gradient-to":
            out.append(f"--tw-gradient-to:var(--o-{role}-{step}) var(--tw-gradient-to-position)")
        else:
            out.append(f"{prop}:var(--o-{role}-{step})")
    rules.append(f"{selector}{{{';'.join(out)}}}")
header = "/* Generated by scripts/gen_elementary_palette.py - do not edit. */\n"
(root / "static/css/elementary-palette.css").write_text(header + "\n".join(rules) + "\n")
print(len(rules), "rules")
